const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {pathToFileURL}=require('node:url');

(async()=>{
  const html=path.resolve(__dirname,'..','GENUS_TWO_LOW_SECTOR_PAIRING_EXPLORER.html');
  const browserChannel=process.env.MOSAIC_BROWSER_CHANNEL||'msedge';
  const browser=await chromium.launch({channel:browserChannel,headless:true});
  const context=await browser.newContext({viewport:{width:1240,height:1000},offline:true,colorScheme:'light'});
  const page=await context.newPage(),requests=[],errors=[];
  page.on('request',r=>{if(!r.url().startsWith('file:'))requests.push(r.url())});
  page.on('pageerror',e=>errors.push(String(e)));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
  await page.goto(pathToFileURL(html).href);
  await page.waitForSelector('#hero-eq');
  assert.equal(await page.locator('main h2').count(),6,'semantic station headings');
  const nonclaims=await page.textContent('#s-non');
  assert.match(nonclaims,/deliberate review boundary/);
  assert.match(nonclaims,/no dynamical admissibility is asserted/);
  assert.match(nonclaims,/initial sector is H1 or H2/);
  assert.match(nonclaims,/no integral or mod-2 geometric map has been identified/);
  assert.doesNotMatch(nonclaims,/admissible numerical fixtures/);
  assert.doesNotMatch(nonclaims,/The algebra is integral/);
  assert.match(await page.textContent('#hero-eq'),/=\s*1/);
  assert.equal(await page.locator('#junction tbody tr').count(),8);
  assert.deepEqual(await page.locator('.col .res b').allTextContents(),['0 mismatches','0 mismatches','1 mismatch']);
  assert.match(await page.textContent('#flow-status'),/Source F₁\(u\)/);
  assert.doesNotMatch(await page.textContent('#flow-status'),/has 0 terms/);
  if(process.env.CBMD_ECH_SCREENSHOTS){fs.mkdirSync(process.env.CBMD_ECH_SCREENSHOTS,{recursive:true});await page.screenshot({path:path.join(process.env.CBMD_ECH_SCREENSHOTS,'pairing-explorer-wide.png'),fullPage:true});}
  await page.locator('[data-coord="corrected"]').click();
  assert.match(await page.textContent('#matrix-note'),/block diagonal/);
  await page.locator('#b-seg button').nth(3).click();
  assert.match(await page.textContent('#hero-eq'),/=\s*1/);
  await page.locator('#g-seg button').nth(1).click();
  await page.locator('#d-seg button').nth(0).click();
  assert.match(await page.textContent('#summary'),/outside D = 0/);
  assert.match(await page.textContent('#flow-status'),/requires D ≥ 1/);
  await page.locator('#d-seg button').nth(3).click();
  await page.locator('#eps').evaluate(el=>{el.value='.75';el.dispatchEvent(new Event('input',{bubbles:true}))});
  assert.match(await page.textContent('#action-status'),/not excluded/);
  await page.locator('[data-preset="flow"]').click();
  assert.match(await page.locator('#src-mono option:checked').textContent(),/^u/);
  await page.locator('#flow-source').selectOption('selected');
  assert.doesNotMatch(await page.textContent('#flow-status'),/has 0 terms/);
  await page.setViewportSize({width:360,height:1000});
  await page.emulateMedia({colorScheme:'dark',reducedMotion:'reduce'});
  if(process.env.CBMD_ECH_SCREENSHOTS)await page.screenshot({path:path.join(process.env.CBMD_ECH_SCREENSHOTS,'pairing-explorer-mobile-dark.png'),fullPage:true});
  const geometry=await page.evaluate(()=>({client:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth,offenders:[...document.querySelectorAll('body *:not(svg):not(svg *)')].map(e=>({tag:e.tagName,id:e.id,cls:String(e.className||''),left:e.getBoundingClientRect().left,right:e.getBoundingClientRect().right,width:e.getBoundingClientRect().width,scroll:e.scrollWidth,client:e.clientWidth})).filter(x=>x.right>document.documentElement.clientWidth+1||x.left< -1||x.scroll>x.client+1).sort((a,b)=>b.right-a.right).slice(0,20)}));
  assert.ok(geometry.scroll<=geometry.client+1,JSON.stringify(geometry));
  assert.deepEqual(requests,[],'no non-file requests');
  assert.deepEqual(errors,[],'no page or console errors');
  console.log(JSON.stringify({status:'PASS',browser_channel:browserChannel,external_requests:requests.length,page_errors:errors,viewports:[1240,360],dark_mode:true,station_headings:6,review_boundary_copy:'asserted',default_flow:'nonzero three-step example',responsive:geometry}));
  await browser.close();
})().catch(error=>{console.error(error);process.exitCode=1});
