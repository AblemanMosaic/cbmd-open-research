"""Monomial (imprimitive, Blichfeldt types C and D) finite subgroups G of SL_3(C), up to diagonal
conjugation, with diagonal part A = G cap T of order <= NMAX: exact critical-group orders.

Normal form (written argument, Section 'Monomial case'):
  * A is a finite subgroup of the diagonal torus T of SL_3 stable under coordinate permutations of
    the permutation image H (C3 or S3); here we require S3-stability for type D and C3-stability
    for type C;
  * after conjugating by a diagonal matrix, the lift of the 3-cycle is the permutation matrix P_s;
  * type C:  G = A x| <P_s>;
  * type D:  G = <A, P_s, t>, t = D_d P_t (P_t the transposition (1 2)), det t = 1, with d in
    mu_{2n}^3 (n = |A|) satisfying d tau(d) in A and d / s(d) in A; one t per class modulo A.

For each G: elements by closure (as (permutation, exponent vector mod M)), conjugacy classes by brute
force, |G^ab| = |G| / |[G,G]|, multiplicity of the trivial character, real-valuedness of the
character, and P = prod_{c != 1} (3 - chi(c)) (numerically with mpmath, 60 digits, then rounded;
the rounding error is reported).  Minimal  <=>  P = |G| |G^ab|.

usage: python3 monomial_enum.py NMAX [out.jsonl]
"""
import itertools
import json
import sys
from math import gcd

import mpmath

mpmath.mp.dps = 60
PERMS = list(itertools.permutations(range(3)))
SIGN = {p: (1 if sum(1 for i in range(3) for j in range(i + 1, 3) if p[i] > p[j]) % 2 == 0 else -1) for p in PERMS}
S = (1, 2, 0)        # 3-cycle i -> S[i]
TAU = (1, 0, 2)      # transposition (1 2)
ID = (0, 1, 2)


def compose(p, q):   # (p o q)(i) = p(q(i))
    return tuple(p[q[i]] for i in range(3))


def act(p, w):       # (p . w)_{p(i)} = w_i
    out = [0, 0, 0]
    for i in range(3):
        out[p[i]] = w[i]
    return tuple(out)


class Mono:
    """g = D_v P_p with P_p e_i = e_{p(i)}, entries zeta_M^{v_i}."""

    def __init__(self, M):
        self.M = M

    def mul(self, x, y):
        (p, v), (q, w) = x, y
        pw = act(p, w)
        return (compose(p, q), tuple((v[i] + pw[i]) % self.M for i in range(3)))

    def inv(self, x):
        p, v = x
        pinv = tuple(sorted(range(3), key=lambda i: p[i]))
        # (D_v P_p)^-1 = P_p^-1 D_-v = D_{p^-1 . (-v)} P_p^-1
        w = act(pinv, tuple((-vi) % self.M for vi in v))
        return (pinv, w)

    def trace(self, x):
        p, v = x
        return sum(mpmath.expjpi(2 * mpmath.mpf(v[i]) / self.M) for i in range(3) if p[i] == i)

    def closure(self, gens, limit=10 ** 6):
        e = (ID, (0, 0, 0))
        elems = {e}
        frontier = [e]
        while frontier:
            nxt = []
            for x in frontier:
                for g in gens:
                    y = self.mul(x, g)
                    if y not in elems:
                        elems.add(y)
                        nxt.append(y)
                        if len(elems) > limit:
                            return None
            frontier = nxt
        return elems


def subgroups_of_order(n):
    """Subgroups of order n of T[n] = {(a,b,c) in (Z/n)^3, a+b+c=0} ~ (Z/n)^2 via (a,b).
    HNF rows (a1, b1), (0, d1) with a1 d1 = n, 0 <= b1 < d1 generate the lattice L containing n Z^2;
    the subgroup is L / n Z^2 (order n^2 / (a1 d1) = n)."""
    for a1 in range(1, n + 1):
        if n % a1:
            continue
        d1 = n // a1
        for b1 in range(d1):
            yield ((a1, b1), (0, d1))


def members(gens2, n):
    """all elements (a, b, c) of the subgroup of (Z/n)^2 generated by the rows of gens2."""
    (a1, b1), (a2, b2) = gens2
    out = {(0, 0)}
    frontier = [(0, 0)]
    while frontier:
        nxt = []
        for (a, b) in frontier:
            for (x, y) in ((a1, b1), (a2, b2)):
                z = ((a + x) % n, (b + y) % n)
                if z not in out:
                    out.add(z)
                    nxt.append(z)
        frontier = nxt
    return {(a, b, (-a - b) % n) for (a, b) in out}


def analyse(mono, G):
    G = list(G)
    idx = {g: i for i, g in enumerate(G)}
    inv = [mono.inv(g) for g in G]
    seen = [False] * len(G)
    classes = []
    for i, x in enumerate(G):
        if seen[i]:
            continue
        cl = set()
        for j, g in enumerate(G):
            y = mono.mul(mono.mul(g, x), inv[j])
            cl.add(idx[y])
        for k in cl:
            seen[k] = True
        classes.append(sorted(cl))
    e = idx[(ID, (0, 0, 0))]
    tr = [mono.trace(G[c[0]]) for c in classes]
    P = mpmath.mpc(1)
    for c, t in zip(classes, tr):
        if e in c:
            continue
        P *= (3 - t)
    triv = sum(len(c) * t for c, t in zip(classes, tr)) / len(G)
    real = all(abs(mpmath.im(t)) < mpmath.mpf('1e-40') for t in tr)
    comm = {mono.mul(mono.mul(x, y), mono.mul(mono.inv(x), mono.inv(y))) for x in G for y in G}
    D = mono.closure(list(comm))
    Pint = int(mpmath.nint(mpmath.re(P)))
    err = float(abs(P - Pint))
    return {'order': len(G), 'classes': len(classes), 'P': Pint, 'P_rounding_error': err,
            'Gab': len(G) // len(D), 'trivial_multiplicity': int(mpmath.nint(mpmath.re(triv))),
            'real_character': bool(real)}


def main():
    nmax = int(sys.argv[1])
    out = open(sys.argv[2], 'w') if len(sys.argv) > 2 else None
    total = {'C': 0, 'D': 0}
    minimal = []
    for n in range(1, nmax + 1):
        M = 2 * n  # diagonal entries of all elements lie in mu_{2n} (see docstring)
        mono = Mono(M)
        scale = M // n
        for gens2 in subgroups_of_order(n):
            A = members(gens2, n)
            if len(A) != n:
                raise RuntimeError('subgroup size')
            stableC = all(act(S, a) in A for a in A)
            if not stableC:
                continue
            stableD = all(act(TAU, a) in A for a in A)
            Agens = [(ID, tuple((scale * x) % M for x in a)) for a in A]
            Ps = (S, (0, 0, 0))
            # type C
            G = mono.closure(Agens + [Ps])
            if len(G) != 3 * n:
                raise RuntimeError('type C order')
            r = analyse(mono, G)
            r.update({'type': 'C', 'A_order': n, 'A_hnf': gens2})
            total['C'] += 1
            if out:
                out.write(json.dumps(r) + '\n')
            if r['P'] == r['order'] * r['Gab']:
                minimal.append(r)
            if not stableD:
                continue
            # type D: t = D_d P_tau with det t = 1:  sign(tau) zeta^{sum d} = 1  ->  sum d = M/2
            Aset = {tuple((scale * x) % M for x in a) for a in A}
            reps = []
            seen_cls = set()
            for d0 in range(M):
                for d1 in range(M):
                    d2 = (M // 2 - d0 - d1) % M
                    d = (d0, d1, d2)
                    dt = tuple((d[i] + act(TAU, d)[i]) % M for i in range(3))
                    if dt not in Aset:
                        continue
                    t = (TAU, d)
                    x = mono.mul(mono.mul(mono.mul(t, Ps), mono.inv(t)), Ps)
                    if x[0] != ID or x[1] not in Aset:
                        continue
                    key = min(tuple((d[i] + a[i]) % M for i in range(3)) for a in Aset)
                    if key in seen_cls:
                        continue
                    seen_cls.add(key)
                    reps.append(d)
            for d in reps:
                t = (TAU, d)
                G = mono.closure(Agens + [Ps, t])
                if G is None or len(G) != 6 * n:
                    continue
                r = analyse(mono, G)
                r.update({'type': 'D', 'A_order': n, 'A_hnf': gens2, 't_exponents': d, 'M': M})
                total['D'] += 1
                if out:
                    out.write(json.dumps(r) + '\n')
                if r['P'] == r['order'] * r['Gab']:
                    minimal.append(r)
        if out:
            out.flush()
        print(f'n={n} done; groups so far C={total["C"]} D={total["D"]}; minimal so far {len(minimal)}', flush=True)
    for r in minimal:
        print('MINIMAL', json.dumps(r))
    print('TOTAL', json.dumps(total))


if __name__ == '__main__':
    main()
